export function lessonId(n) {
  return `districtCourseLesson.district-course-l${String(n).padStart(2, '0')}`;
}

export function moduleForLesson(n) {
  return MODULES.find((m) => m.lessonNumbers.includes(n));
}

export function moduleOrderForLesson(n) {
  const mod = moduleForLesson(n);
  if (!mod) return n;
  return mod.lessonNumbers.indexOf(n) + 1;
}

/** ISO datetime для scheduledAt (18:00 Minsk, UTC+3). */
export function scheduledAtFromDate(dateStr) {
  return `${dateStr}T18:00:00+03:00`;
}
