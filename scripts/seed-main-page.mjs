// ---------- Создание ----------
try {
  // Синглтоны: создаём только если документа с таким _id ещё нет.
  for (const doc of docs) {
    const res = await client.createIfNotExists(doc);
    console.log(`${res.results?.[0]?.operation === 'none' ? 'пропущен (уже есть)' : 'создан'}: ${doc._type}`);
  }

  // Вопросы FAQ: создаём, только если в датасете пока нет ни одного.
  const faqCount = await client.fetch('count(*[_type == "faqItem"])');
  if (faqCount > 0) {
    console.log(`пропущены: вопросы FAQ (уже существует ${faqCount})`);
  } else {
    const items = faqItems.map((item, index) => ({
      _type: 'faqItem',
      question: item.question,
      answer: item.answer,
      order: index + 1,
    }));
    for (const item of items) {
      await client.create(item);
    }
    console.log(`созданы: ${items.length} вопросов FAQ`);
  }

  console.log('\nГотово. Документы видны в Studio: /studio');
} catch (err) {
  console.error('Ошибка при создании документов:', err?.message ?? err);
  process.exit(1);
}
